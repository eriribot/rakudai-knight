import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { read, samples } from './mvu-model.mjs';
const context = { window: {}, structuredClone };
for (const file of ['data.js', 'session-bracket.js']) vm.runInNewContext(fs.readFileSync(new URL(file, import.meta.url), 'utf8'), context);
const { RK_PREVIEW_BRACKET: engine, TOURNAMENT_DATA: canon } = context.window;
const reps = read(samples.qualified.state).qualification.representatives;
const bracket = engine.create(canon, reps);
assert.equal(bracket.slots.flat().length, 32);
assert.equal(new Set(bracket.slots.flat()).size, 32);
assert.equal(bracket.slots.flat().filter(id => bracket.players[id].player).length, 1);
assert.equal(bracket.slots.flat().filter(id => bracket.players[id].school === '破军学园').length, 6);
assert.ok(bracket.matches.every(m => m.winner === null));
const mine = bracket.matches.find(m => [m.p1, m.p2].some(id => bracket.players[id]?.player));
const playerId = [mine.p1, mine.p2].find(id => bracket.players[id]?.player);
const next = bracket.matches.find(m => m.from.includes(mine.id));
engine.settle(bracket, mine.id, playerId);
assert.ok([next.p1, next.p2].includes(playerId));
const sibling = bracket.matches.find(m => m.id === next.from.find(id => id !== mine.id));
engine.settle(bracket, sibling.id, sibling.p1);
engine.settle(bracket, next.id, playerId);
assert.equal(next.winner, playerId);
const lostTo = mine.p1 === playerId ? mine.p2 : mine.p1;
engine.settle(bracket, mine.id, lostTo);
assert.equal(next.winner, null);
assert.ok([next.p1, next.p2].includes(lostTo));
assert.ok(![next.p1, next.p2].includes(playerId));
const later = bracket.matches.find(m => m.from.includes(next.id));
assert.ok(![later.p1, later.p2].includes(playerId));
const empty = engine.create(canon, []);
const vacant = empty.matches.find(m => [m.p1, m.p2].some(id => empty.players[id]?.pending));
engine.settle(empty, vacant.id, vacant.p1);
assert.equal(vacant.winner, null);
assert.equal(canon.players.ikki.player, undefined, '原著资料不被演示修改');
console.log('Preview bracket: 32 unique seats, 6 representatives, one player, no preset winners, result propagation and correction, pending seats passed.');
