import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(fileURLToPath(import.meta.url));
const read = name => readFile(path.resolve(root, name), 'utf8');

// 四个独立闭包保留原模块局部作用域；classic script 可直接随 file:// 预览打开。
function closure(source, imports = '') {
  const exported = [...source.matchAll(/^export\s+(?:function|const|let|class)\s+(\w+)/gm)].map(match => match[1]);
  const body = source.replace(/^import\s+.*?;\s*$/gm, '').replace(/^export\s+/gm, '');
  return '(function(){\n' + imports + '\n' + body + '\nreturn {' + exported.join(',') + '};\n})()';
}

const calendarJson = JSON.parse(await read('../scripts/story/tournament-calendar-2013.json'));
const calendar = closure(await read('../scripts/rakudai-tournament-calendar.mjs'), 'const tournamentCalendar2013=' + JSON.stringify(calendarJson) + ';');
const background = closure(await read('../scripts/rakudai-tournament-background.mjs'), 'const {tournamentCalendar,parseTournamentDate}=calendar;');
const tournament = closure(await read('../scripts/rakudai-tournament.mjs'),
  'const {TOURNAMENT_CANON,identifyTournamentPlayer,seedTournamentRoster,projectTournamentBackground}=background;\nconst {tournamentCalendar,parseTournamentDate,isHagunAffiliation}=calendar;');
const model = closure(await read('mvu-model.mjs'), 'const {deriveTournament}=tournament;\nconst {TOURNAMENT_CANON,seedTournamentRoster}=background;');
const output = '// Generated by build-mvu.mjs. Read-only preview; reuses the existing T02 engine.\n' +
  '(function(){\n"use strict";\nconst calendar=' + calendar + ';\nconst background=' + background + ';\nconst tournament=' + tournament + ';\nconst model=' + model + ';\nwindow.RK_PREVIEW_MVU={samples:model.samples,read:model.read};\n})();\n';
await writeFile(path.join(root, 'mvu-model.js'), output, 'utf8');
console.log('Built mvu-model.js (' + Buffer.byteLength(output) + ' bytes)');
