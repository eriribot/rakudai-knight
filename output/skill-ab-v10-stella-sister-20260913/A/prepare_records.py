    evidence = [cite(line, quote) for line, quote in locations]
    facts.append({'id': identifier, 'claim': claim, 'entry_uid': uid, 'group': group,
                  'status': status, **{k: evidence[0][k] for k in ('line_start','line_end','quote')},
                  'evidence': evidence})

