def cite(line_no, quote):
    line = lines[line_no - 1]
    assert quote in line, (line_no, quote)
    start = line_offsets[line_no - 1] + line.index(quote)
    unit = next(u for u in source['units'] if u['start'] <= start and start + len(quote) <= u['end'])
    assert source_text[start:start + len(quote)] == quote
    return {'line_start': line_no, 'line_end': line_no, 'quote': quote,
            'unit_id': source['id'] + '/' + unit['id'], 'source_sha256': source_hash, 'start': start}

