// Offline contract checks. Browser interaction evidence is recorded separately.
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const source = path.resolve(__dirname, '../第一卷-世界书整理/开局页面/index.html');
const html = fs.readFileSync(source, 'utf8');
const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
scripts.forEach((m, i) => new vm.Script(m[1], { filename: `inline-${i}.js` }));
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
assert.equal(new Set(ids).size, ids.length, 'HTML IDs must be unique');
assert(!/男 U|input-romaji|input-rank|card-gender|DEFAULT_GENDER|romaji/.test(html));
assert(!/src="bgm1\.mp3"/.test(html));
assert(html.includes('https://eriribot.github.io/rakudai-knight/bgm1.mp3'));
const script = scripts.at(-1)[1];
const constants = script.slice(script.indexOf('var ARCHIVE_FORMAT'), script.indexOf('function readOpeningDraft'));
const functions = script.slice(script.indexOf('function readOpeningDraft'), script.indexOf('function showOpeningPreview'));
const ctx = vm.createContext({ START_PROFILES: { kurogane: { name: '黑铁一辉', personality: '温和', conduct: '观察', school: '破军学园', device: '阴铁', nobleArt: '一刀修罗', desc: '原作', stats: { attack: 'F', defense: 'F', magic: 'F', control: 'E', physical: 'A', luck: 'F' } } } });
vm.runInContext(constants + functions, ctx);
const fixture = { format: 'rakudai-opening-profile', schema_version: 2, profile_key: 'user', profile: { name: '测试骑士', personality: '沉静、好胜', conduct: '守约 | /trigger', school: '破军学园', device: '银镜', nobleArt: '折光', desc: '<script>not executable</script>\n第二行', stats: { attack: '', defense: '', magic: '', control: '', physical: '', luck: '' } }, avatar: null };
const clean = ctx.validateArchive(JSON.parse(JSON.stringify(fixture)));
const message = ctx.buildOpeningMessage(clean);
assert(message.includes('黑铁一辉继续作为独立 NPC'));
assert(message.includes('守约 | /trigger'));
assert(!message.includes('伐刀者等级：'));
assert(!('rank' in clean.profile));
assert.equal(JSON.stringify(ctx.validateArchive(JSON.parse(JSON.stringify(clean)))), JSON.stringify(clean));
const badVersion = structuredClone(fixture); badVersion.schema_version = 999;
assert.throws(() => ctx.validateArchive(badVersion));
const badGrade = structuredClone(fixture); badGrade.profile.stats.attack = 'S';
assert.throws(() => ctx.validateArchive(badGrade));
const remotePhoto = structuredClone(fixture); remotePhoto.avatar = 'https://example.com/photo.jpg';
assert.throws(() => ctx.validateArchive(remotePhoto));
const tooLong = structuredClone(fixture); tooLong.profile.name = 'x'.repeat(61);
assert.throws(() => ctx.validateArchive(tooLong));
const canon = structuredClone(fixture); canon.profile_key = 'kurogane'; canon.profile.name = '伪造原作';
const normalizedCanon = ctx.validateArchive(canon);
assert.equal(normalizedCanon.profile.name, '黑铁一辉');
assert.equal(normalizedCanon.profile.rank, 'F');
assert.equal(normalizedCanon.profile.stats.attack, 'F');
console.log(JSON.stringify({ inlineScripts: scripts.length, uniqueIds: ids.length, archiveRoundtrip: 'pass', invalidArchiveRejection: 'pass', canonTemplateProtection: 'pass', customRankOmission: 'pass', remoteBgmOnly: 'pass' }, null, 2));
