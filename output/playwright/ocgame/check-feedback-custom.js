async (page) => {
  const checks=[], errors=[], missing=[];
  page.on('pageerror', e=>errors.push(e.message));
  page.on('response', r=>{if(r.status()>=400)missing.push(r.url());});
  const check=(name,ok,detail)=>{checks.push({name,ok,detail});if(!ok)throw new Error(name+': '+JSON.stringify(detail));};
  const idle=()=>page.locator('#game[data-busy=false]').waitFor();
  await page.setViewportSize({width:799,height:764});
  await page.goto('http://127.0.0.1:4178/');
  await page.locator('#customize').click();
  const classes=await page.locator('#ability-options strong').allTextContents();
  check('five canonical category names',JSON.stringify(classes)===JSON.stringify(['体能强化系','自然干涉系','概念干涉系','因果干涉系','未归类系']),classes);
  await page.locator('#name-input').fill('自定义主角');
  await page.locator('#appearance-input').fill('银色指环，展开后像一把半透明的弓。<b>不作为 HTML</b>');
  await page.locator('[name=abilityClass][value=unclassified]').check();
  check('class changes independently of battle technique',await page.locator('#arcana-input').inputValue()==='insight');
  await page.locator('#avatar-input').setInputFiles('ocgame/assets/references/ayase-official.jpg');
  await page.locator('#avatar-message').filter({hasText:'头像已预览'}).waitFor();
  const validAvatar=await page.locator('#avatar-preview').getAttribute('src');
  check('avatar decodes and previews',validAvatar.startsWith('data:image/jpeg;base64,')&&await page.locator('#avatar-preview').evaluate(i=>i.naturalWidth>0));
  await page.locator('#avatar-input').setInputFiles({name:'invalid.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"/>')});
  check('reject unsupported format without losing draft', (await page.locator('#avatar-message').textContent()).includes('请选择')&&(await page.locator('#avatar-preview').getAttribute('src'))===validAvatar);
  await page.locator('#avatar-input').setInputFiles({name:'oversize.png',mimeType:'image/png',buffer:Buffer.alloc(2*1024*1024+1)});
  check('reject oversize and leave submit enabled', (await page.locator('#avatar-message').textContent()).includes('2 MB')&&!(await page.locator('#profile-submit').isDisabled()));
  await page.locator('#avatar-input').setInputFiles({name:'broken.png',mimeType:'image/png',buffer:Buffer.from('not an image')});
  await page.locator('#avatar-message').filter({hasText:'无法读取'}).waitFor();
  check('decode errors preserve previous valid avatar',await page.locator('#avatar-preview').getAttribute('src')===validAvatar);
  await page.locator('#profile-submit').click();await page.reload();
  let p=await page.evaluate(()=>JSON.parse(localStorage.getItem('ocgame.profile.v1')));
  check('avatar appearance and fifth class persist',p.avatarDataUrl===validAvatar&&p.deviceAppearance.endsWith('<b>不作为 HTML</b>')&&p.abilityClass==='unclassified');
  check('saved avatar appears in battle',await page.locator('#player-avatar').isVisible());
  await page.locator('#customize').click();
  check('appearance rendered as plain text',await page.locator('#passport-appearance b').count()===0&&(await page.locator('#passport-appearance').textContent()).includes('<b>'));
  await page.locator('#avatar-remove').click();
  await page.keyboard.press('Escape');
  await page.locator('#customize').click();
  check('cancelled avatar removal preserves saved profile',await page.locator('#avatar-preview').getAttribute('src')===validAvatar);
  await page.locator('#custom-dialog').evaluate(el=>el.scrollTop=0);
  await page.screenshot({path:'output/playwright/ocgame/feedback-final-registration-avatar.png'});
  await page.locator('#ability-options').scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/ocgame/feedback-final-categories.png'});
  await page.locator('#avatar-remove').click();await page.locator('#profile-submit').click();await page.reload();
  check('saved avatar removal persists',await page.locator('#player-avatar').isHidden());
  for(const [kind,label,damage,remaining] of [['poison','中毒',1,2],['bleed','流血',2,1],['burn','烧伤',2,1]]) {
    await page.locator('#customize').click();
    await page.locator('#attack-status-input').selectOption(kind);
    await page.locator('#profile-submit').click();
    await page.locator('.playing-card[data-kind=slash]').first().click();await idle();
    const badge=page.locator(`#enemy-statuses [data-status=${kind}]`);
    check(`${kind}: actual attack creates live status`,(await badge.textContent()).includes(label));
    await badge.click();
    check(`${kind}: badge opens rule explanation`,(await page.locator('#status-current').textContent()).includes(label+' 1 层'));
    await page.locator('#status-dialog [data-close]').last().click();
    await page.locator('#end-turn').click();await idle();
    check(`${kind}: correct HP and remaining count`,(await page.locator('#enemy-health').textContent())===`${96-damage} / 108`&&(await badge.textContent()).includes(`余 ${remaining}`));
    await page.screenshot({path:`output/playwright/ocgame/feedback-final-${kind}-799.png`,fullPage:true});
    await page.locator('#reset').click();
    check(`${kind}: reset clears status`,await page.locator('#enemy-statuses .condition-badge').count()===0);
  }
  for(let i=0;i<3;i++){await page.locator('#end-turn').click();await idle();}
  check('enemy flame produces a player burn badge',await page.locator('#player-statuses [data-status=burn]').count()===1);
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/playwright/ocgame/feedback-final-player-burn-mobile.png',fullPage:true});
  await page.locator('#customize').click();
  await page.screenshot({path:'output/playwright/ocgame/feedback-final-registration-mobile.png'});
  await page.keyboard.press('Escape');
  await page.locator('#reset').click();
  await page.locator('#support').click();
  await page.locator('#support-cutin[data-stage=portrait]').waitFor();
  await page.waitForTimeout(190);
  await page.screenshot({path:'output/playwright/ocgame/feedback-final-cutin-mobile.png'});
  await idle();
  check('no browser errors or 404s',!errors.length&&!missing.length,{errors,missing});
  await page.evaluate(()=>localStorage.removeItem('ocgame.profile.v1'));
  await page.reload();await page.setViewportSize({width:1440,height:900});
  return {checks,errors,missing};
}
