async (page) => {
  page.setDefaultTimeout(10000);
  const errors = [];
  const badResponses = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) badResponses.push(response.status() + ' ' + response.url()); });
  const url = 'http://127.0.0.1:4177/%E7%81%AB%E7%BA%B9%E6%94%AF%E6%8F%B4%E5%BA%A6/index.html';
  const check = (value, message) => { if (!value) throw new Error(message); };
  const state = () => page.evaluate(() => SupportDemo.state);
  await page.setViewportSize({width:1440,height:1000});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto(url);
  await page.locator('#reset-demo').click();
  check(!(await state()).completed, 'Reset must leave C locked');
  check(await page.locator('.future:disabled').count() === 3, 'Future characters must not launch empty events');
  await page.locator('#support-start').click();
  check(await page.locator('#dialogue-text').textContent() === await page.evaluate(() => SupportDemo.story.lines[0].text), 'First dialogue text was removed or wrong');
  check(await page.locator('#dialogue-count').textContent() === '01 / 18', 'First line counter wrong');
  await page.locator('#dialogue-next').press('Enter');
  check((await state()).index === 1, 'Enter should advance once');
  await page.keyboard.press('Escape');
  check((await state()).screen === 'hub' && !(await state()).completed, 'Early exit must not unlock C');
  await page.locator('#support-start').click();
  await page.locator('#auto-play').click();
  await page.waitForFunction(() => SupportDemo.state.index === 1, {timeout:10000});
  await page.locator('#open-log').click();
  check((await state()).logOpen && !(await state()).autoPlay, 'Log must pause autoplay');
  check(await page.locator('.log-entry').count() === 2, 'Log must contain read lines only');
  await page.keyboard.press('Escape');
  check(!(await state()).logOpen && (await state()).screen === 'event', 'Escape from log must not leave event');
  check(!(await state()).autoPlay, 'Closing log must not resume autoplay');
  await page.locator('#dialogue-next').press('Space');
  check((await state()).index === 2, 'Space should advance once');
  for (let n = 2; n < 17; n++) await page.locator('#dialogue-next').click();
  check((await state()).index === 17 && !(await state()).completed, 'Reading final line alone must not settle');
  await page.locator('#dialogue-next').click();
  check((await state()).screen === 'result' && (await state()).completed, 'Final continue must unlock C');
  await page.screenshot({path:'output/playwright/support-result.png',fullPage:true});
  const saved = await page.evaluate(() => localStorage.getItem('rakudai-support-demo-v1'));
  check(JSON.parse(saved).completed === true, 'Completion must persist');
  await page.locator('#result-replay').click();
  for (let n = 0; n < 18; n++) await page.locator('#dialogue-next').click();
  check(await page.evaluate(() => localStorage.getItem('rakudai-support-demo-v1')) === saved, 'Replay must not re-award or rewrite completion');
  await page.locator('#result-back').click();
  await page.reload();
  check((await state()).completed && await page.locator('#rank-current').textContent() === 'C', 'Reload must restore completed C');
  await page.locator('#reset-demo').click();
  await page.emulateMedia({reducedMotion:'no-preference'});
  // Freeze time so driver latency cannot finish the line before the test click.
  await page.clock.install();
  await page.clock.pauseAt(Date.now());
  await page.locator('#support-start').click();
  check((await state()).typing, 'Normal mode needs typewriter');
  await page.locator('#dialogue-next').click();
  check((await state()).index === 0 && !(await state()).typing, 'First click while typing must complete the same line');
  await page.clock.resume();
  await page.waitForFunction(() => document.querySelector('#portrait-stella').dataset.layersReady === 'true');
  const readyImages = await page.evaluate(() => [...document.images].every(image => image.complete && image.naturalWidth > 0));
  check(readyImages, 'Every portrait must decode');
  await page.screenshot({path:'output/playwright/support-event-desktop.png',fullPage:true});
  const geometry = [];
  for (const viewport of [{width:1024,height:768},{width:844,height:390},{width:390,height:844}]) {
    await page.setViewportSize(viewport);
    await page.screenshot({path:'output/playwright/support-event-' + viewport.width + '.png',fullPage:true});
    geometry.push(await page.evaluate(() => {
      const stage = document.querySelector('#portrait-stella .portrait-rig').getBoundingClientRect();
      const eyes = document.querySelector('.eye-layer').getBoundingClientRect();
      const box = document.querySelector('#dialogue-next').getBoundingClientRect();
      return {viewport:innerWidth,overflow:document.documentElement.scrollWidth > innerWidth,eyeWidth:eyes.width / stage.width,dialogue:{left:box.left,right:box.right,bottom:box.bottom},loaded:document.querySelector('#portrait-stella').dataset.layersReady};
    }));
  }
  check(geometry.every(g => !g.overflow && g.dialogue.left >= 0 && g.dialogue.right <= g.viewport), 'Responsive dialogue must fit without horizontal overflow');
  check(geometry.every(g => Math.abs(g.eyeWidth - 153/1024) < .002), 'Facial coordinates must remain constant while resizing');
  await page.locator('#leave-event').click();
  await page.screenshot({path:'output/playwright/support-hub-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'output/playwright/support-desktop.png',fullPage:true});
  await page.locator('#support-start').click();
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(() => SupportDemo.state.reducedMotion && !SupportDemo.state.typing);
  check(!(await state()).typing, 'Enabling reduced motion must stop typing');
  check(await page.locator('.eye-layer').evaluate(el => getComputedStyle(el).display) === 'none', 'Reduced motion must suppress blinking');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.locator('#portrait-stella .portrait-rig').evaluate(el => {
    el.style.animation = 'none';
    el.querySelectorAll('.face-layer').forEach(layer => {layer.style.animation='none';layer.style.display='block';layer.style.opacity='1';});
  });
  await page.locator('#portrait-stella .portrait-rig').screenshot({path:'output/playwright/support-stella-closed-speaking.png'});
  await page.reload();
  const privatePage = await page.context().newPage();
  await privatePage.addInitScript(() => { Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Blocked','SecurityError');}}); });
  await privatePage.goto(url);
  await privatePage.emulateMedia({reducedMotion:'reduce'});
  await privatePage.locator('#support-start').click();
  for (let n=0;n<18;n++) await privatePage.locator('#dialogue-next').click();
  check(await privatePage.evaluate(() => SupportDemo.state.completed && !SupportDemo.state.storageUsable), 'Blocked storage must still allow complete play');
  await privatePage.close();
  await page.goto('file:///D:/card/rakudai-knight/cardgame/%E7%81%AB%E7%BA%B9%E6%94%AF%E6%8F%B4%E5%BA%A6/index.html');
  await page.locator('#support-start').click();
  check((await state()).screen === 'event', 'Direct file opening must work');
  check(await page.evaluate(() => [...document.images].every(image=>image.complete&&image.naturalWidth>0)), 'Direct file assets must load');
  await page.goto(url);
  await page.locator('#reset-demo').click();
  check(!errors.length, 'Browser errors: '+errors.join('; '));
  check(!badResponses.length, 'Failed resources: '+badResponses.join('; '));
  return {status:'passed',checks:['early exit','keyboard','auto','log','completion','persistence','replay idempotence','reset','typewriter','facial layers','responsive geometry','reduced motion','blocked storage','file opening'],geometry,pageErrors:errors,failedResponses:badResponses};
}
