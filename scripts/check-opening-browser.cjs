    await page.locator('#nav-step-3').click();
    assert.equal(await page.locator('#scene-register').isVisible(),true);
    assert.equal(await page.locator('#scene-confirm').isVisible(),false);
    assert.equal(await page.locator('#rating-assistant-tools').count(),0);
    assert.equal(await page.locator('#scene-register [required]').count(),16);
    await page.locator('#ai-assistance summary').click();
    const aiButton=page.getByRole('button',{name:'AI 生成并填写',exact:true});
    await aiButton.click();
    assert.match(await page.locator('#ai-assistance-status').innerText(),/未检测到/);
