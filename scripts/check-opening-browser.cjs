    assert.match(message,/入学报到那天/);
    assert.match(message,/综合初评：B/);
    assert.doesNotMatch(message,/待复核|拟定登记等级|request_id/);
    checks.push('all six axes required/whitespace rejected/automatic B/bio in message');
