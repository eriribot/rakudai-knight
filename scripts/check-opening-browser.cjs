// Local Chrome acceptance. Pass the installed Playwright package path if not on NODE_PATH.
const {chromium} = require(process.argv[2] || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const output = path.resolve(__dirname, '../output/playwright/rating-v03');
fs.mkdirSync(output, {recursive:true});
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true});
  const context = await browser.newContext({viewport:{width:1280,height:900}, acceptDownloads:true});
  const page = await context.newPage();
  page.setDefaultTimeout(7000);
  const errors = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  // Media is deliberately unavailable: form and saving must not depend on remote assets.
  await page.route('https://**/*', r => r.abort());
  try {
    await page.goto(process.argv[3] || 'http://127.0.0.1:8770/第一卷-世界书整理/开局页面/index.html?scene=2', {waitUntil:'domcontentloaded'});
    await page.getByRole('button', {name:'CLICK TO SKIP'}).click();
    await page.getByRole('button', {name:'PRESS ANY KEY TO CONTINUE'}).click();
    await page.getByLabel('姓名',{exact:true}).fill('测试骑士');
    await page.getByLabel('能力机制',{exact:true}).fill('在十米内操纵水流，形成水壁并限制对手行动');
    await page.getByLabel('限制与代价',{exact:true}).fill('需要现成的水，维持多个水团会分散控制');
    await page.getByLabel('战斗风格',{exact:true}).fill('中距离防守与牵制');
    for (const [name,value] of Object.entries({'攻击力':'D','防御力':'B','魔力量':'C','魔力控制':'A','体能':'E','运气':'C'})) await page.getByRole('combobox',{name,exact:true}).selectOption(value);
    assert.match(await page.locator('#rating-summary').innerText(), /综合初评 B.*待能力?复核|综合初评 B.*待能力复核|综合初评 B.*待.*复核/);
    checks.push('live initial B');
    await page.getByText('让 AI 帮我评定',{exact:true}).click();
    await page.getByRole('button',{name:'生成并复制评定请求'}).click();
    const request = await page.getByLabel('评定请求（可手动复制）').inputValue();
    const response = JSON.parse(request.split('返回格式：')[1].trim());
    // Deterministic response fixture, not a claim that a live AI generated these judgments.
    response.stats = {attack:'D',defense:'B',magic:'C',control:'A',physical:'E',luck:'C'};
    response.reasons = Object.fromEntries(Object.keys(response.stats).map(k => [k,'用于验证往返链路的测试依据，不是实机 AI 判定']));
    response.adjustment = 0;
    response.reviewReason = '维持 B：能力价值已经体现在六维，不重复奖励';
    await page.getByLabel('粘贴 AI 的评定 JSON').fill(JSON.stringify(response));
    await page.getByRole('button',{name:'核对并应用评定'}).click();
    assert.match(await page.locator('#rating-summary').innerText(), /拟定登记 B/);
    checks.push('response fixture applied');
    const reviewed = await page.evaluate(() => readOpeningDraft());
    assert.equal(reviewed.schema_version, 3);
    assert.equal(reviewed.profile.rating.proposed, 'B');
    assert.equal('rank' in reviewed.profile, false);
    await page.getByRole('button',{name:'下一步：确认档案与正式授印 ➔'}).click();
    assert.equal(await page.locator('#card-rank-val').innerText(), 'B');
    assert.match(await page.locator('#opening-message').inputValue(), /拟定登记等级：B/);
    await page.getByRole('button',{name:'保存到档案槽 1',exact:true}).click();
    const slot = await page.evaluate(() => JSON.parse(localStorage.getItem('rakudai-opening-profiles-v2-slot-1')));
    assert.deepEqual(slot.draft.profile.rating, reviewed.profile.rating);
    checks.push('card/message/slot parity');
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button',{name:'导出档案 JSON',exact:true}).click();
    const jsonDownload = await downloadPromise;
    await jsonDownload.saveAs(path.join(output,'sample-profile.json'));
    assert.deepEqual(JSON.parse(fs.readFileSync(path.join(output,'sample-profile.json'),'utf8')).profile, reviewed.profile);
    const imagePromise = page.waitForEvent('download');
    await page.getByRole('button',{name:'保存档案图片',exact:true}).click();
    await (await imagePromise).saveAs(path.join(output,'sample-profile.png'));
    const image = fs.readFileSync(path.join(output,'sample-profile.png'));
    assert.equal(image.subarray(1,4).toString(), 'PNG');
    checks.push('JSON/PNG export');
    await page.locator('#main-character-card').screenshot({path:path.join(output,'desktop-card.png')});
    await page.getByRole('button',{name:'② 档案登记'}).click();
    await page.getByLabel('限制与代价',{exact:true}).fill('新限制：只能维持一面水壁');
    assert.match(await page.locator('#rating-summary').innerText(), /待.*复核/);
    await page.getByLabel('粘贴 AI 的评定 JSON').fill(JSON.stringify(response));
    await page.getByRole('button',{name:'核对并应用评定'}).click();
    assert.match(await page.locator('#rating-feedback').innerText(), /不对应当前档案/);
    assert.equal((await page.evaluate(() => readOpeningDraft())).profile.assessment, null);
    checks.push('edit invalidation/stale reply rejection');
    await page.getByRole('combobox',{name:'魔力量',exact:true}).selectOption('');
    assert.match(await page.locator('#rating-summary').innerText(), /待评定.*魔力量/);
    await page.getByRole('combobox',{name:'攻击力',exact:true}).selectOption('C+');
    assert.equal((await page.evaluate(() => readOpeningDraft())).profile.stats.attack, 'C+');
    checks.push('plus and missing axis');
    const imports = await page.evaluate((saved) => {
      const v2 = JSON.parse(JSON.stringify(saved)); v2.schema_version=2;
      delete v2.profile.ability; delete v2.profile.limits; delete v2.profile.style;
      const migrated = validateArchive(v2);
      const forged = JSON.parse(JSON.stringify(saved)); forged.profile.rank='S'; forged.profile.rating={base:'A',proposed:'S'};
      const checked = validateArchive(forged);
      const canon = JSON.parse(JSON.stringify(saved)); canon.profile_key='kurogane'; canon.profile.stats.attack='A';
      const protectedCanon = validateArchive(canon);
      let rejected=false;
      try { validateArchive({...saved,profile:{...saved.profile,assessment:{...saved.profile.assessment,adjustment:2}}}); } catch (_) {rejected=true;}
      applyOpeningDraft(migrated);
      return {migrated,checked,protectedCanon,rejected};
    }, reviewed);
    assert.equal(imports.migrated.profile.ability, '');
    assert.equal(imports.migrated.profile.assessment, null);
    assert.equal(imports.checked.profile.rating.proposed, 'B');
    assert.equal('rank' in imports.checked.profile, false);
    assert.equal(imports.protectedCanon.profile.rank, 'F');
    assert.equal(imports.protectedCanon.profile.stats.attack, 'F');
    assert.equal(imports.rejected, true);
    checks.push('v2 migration/forged cache rejection/canon protection');
    await page.getByRole('button',{name:'正典 · 黑铁一辉'}).click();
    assert.equal(await page.getByLabel('能力机制',{exact:true}).getAttribute('readonly'), '');
    assert.equal(await page.locator('#rating-panel').isVisible(), false);
    await page.getByRole('button',{name:'玩家 U',exact:true}).click();
    assert.equal(await page.getByLabel('能力机制',{exact:true}).inputValue(), '');
    await page.evaluate((saved) => applyOpeningDraft(validateArchive(saved)), reviewed);
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'下一步：确认档案与正式授印 ➔'}).click();
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
    assert.equal(overflow, false);
    await page.locator('#main-character-card').screenshot({path:path.join(output,'mobile-card.png')});
    checks.push('canon switch/reset/mobile overflow');
    assert.deepEqual(errors, []);
    const result = {status:'PASS',checks,jsErrors:errors,externalMedia:'blocked intentionally',aiResponse:'fixture only',sillyTavernVerified:false};
    fs.writeFileSync(path.join(output,'result.json'),JSON.stringify(result,null,2));
    console.log(JSON.stringify(result,null,2));
  } catch(error) {
    await page.screenshot({path:path.join(output,'failure.png')}).catch(()=>{});
    console.error(JSON.stringify({checks,errors,message:error.message,body:await page.locator('body').innerText()},null,2));
    process.exitCode=1;
  } finally { await browser.close(); }
})();
