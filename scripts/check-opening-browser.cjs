    await page.locator('#input-ability').fill('正在编辑');
    await page.evaluate(()=>window.resolveAi(JSON.stringify({ability:'旧回复',limits:'代价',style:'战斗',stats:{attack:'A',defense:'A',magic:'A',control:'A',physical:'A',luck:'A'},reasons:'理由'})));
